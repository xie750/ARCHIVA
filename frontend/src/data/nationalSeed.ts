import type { Building } from '../types/building'
import { resolveModelMetadata } from './building3dAssets'
import { verifiedHeritageImages } from './heritageImages'
import { wikimediaHeritageImages } from './wikimediaHeritageImages'

type SeedInput = Pick<Building,
  | 'id'
  | 'region'
  | 'name'
  | 'pinyin'
  | 'category'
  | 'era'
  | 'location'
  | 'coordinates'
  | 'period'
  | 'summary'
  | 'story'
  | 'coverClass'
  | 'image'
  | 'accent'
  | 'metrics'
  | 'tags'
  | 'highlights'
  | 'status'
  | 'model'
>

const sharedTags = ['中国建筑', '民生建筑', '公共空间', '全国索引', '真实资料']

function seed(input: SeedInput): Building {
  const image = input.image ?? verifiedHeritageImages[input.id] ?? wikimediaHeritageImages[input.id]

  return {
    ...input,
    image,
    model: resolveModelMetadata(input.id, input.model),
    tags: Array.from(new Set([...input.tags, ...sharedTags])),
    sources: [{ label: image ? '全国建筑索引资料 · 真实公开影像已接入' : '全国建筑索引资料 · 影像来源待核验', kind: '项目记录' }],
  }
}

const indexModel = (kind: Building['model']['kind'], precision = '信息索引 · 3D 资产排队中'): Building['model'] => ({
  kind,
  version: '0.1.0-index',
  precision,
  nodes: 0,
  provider: 'pending',
  assetStatus: 'pending',
  source: '全国建筑索引；已用于搜索、地图和省级入口展示',
  license: '3D 正式发布前需补充权属与测绘资料',
})

type IconicInput = Omit<SeedInput, 'image' | 'metrics' | 'model' | 'status'> & {
  modelKind: Building['model']['kind']
  metrics?: Building['metrics']
  precision?: string
  status?: Building['status']
}

const iconic = (input: IconicInput): Building => seed({
  ...input,
  status: input.status ?? '持续研究',
  metrics: input.metrics ?? [
    { label: '类型', value: input.category },
    { label: '城市', value: input.location.split(' · ')[0] },
    { label: '索引状态', value: '扩展样本' },
  ],
  model: indexModel(input.modelKind, input.precision ?? '标志性建筑索引 · 3D 资产排队中'),
})

